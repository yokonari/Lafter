// すべてのNGワードを結合
const ALL_NG_WORDS = [...SEXUAL_WORDS, ...OFFENSIVE_WORDS, ...SEXUAL_WORDS_BOPO, ...SEXUAL_WORDS_MASKED];

// 検索用の正規表現を事前コンパイル（大文字小文字を区別しない）
const NG_WORDS_REGEX = new RegExp(
    ALL_NG_WORDS.map(word => escapeRegex(word)).join("|"),
    "i"
);

/**
 * 正規表現のメタ文字をエスケープ
 */
function escapeRegex(str: string): string {
    return str.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

/**
 * 文字列にNGワードが含まれているかチェック
 * @param text チェック対象の文字列
 * @returns NGワードが含まれている場合はtrue
 */
export function containsNgWord(text: string): boolean {
    if (!text) return false;
    return NG_WORDS_REGEX.test(text);
}

/**
 * 文字列からNGワードを検出して返す
 * @param text チェック対象の文字列
 * @returns 検出されたNGワードの配列（見つからない場合は空配列）
 */
export function findNgWords(text: string): string[] {
    if (!text) return [];

    const found: string[] = [];
    for (const word of ALL_NG_WORDS) {
        if (text.toLowerCase().includes(word.toLowerCase())) {
            found.push(word);
        }
    }
    return found;
}
